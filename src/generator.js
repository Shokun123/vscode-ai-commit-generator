/**
 * AI Commit & Changelog Generator Engine
 * Transforms raw Git diffs into semantic Conventional Commits.
 */

export function generateCommitMessage(diffText, options = {}) {
  const { style = 'angular', isPro = false } = options;

  if (!diffText || diffText.trim().length === 0) {
    return {
      type: 'chore',
      scope: 'workspace',
      subject: 'update project files',
      fullMessage: 'chore(workspace): update project files'
    };
  }

  const lines = diffText.split('\n');
  const filesChanged = [];
  let additions = 0;
  let deletions = 0;
  let hasDocs = false;
  let hasTests = false;
  let hasFix = false;
  let hasFeat = false;
  let hasRefactor = false;

  for (const line of lines) {
    if (line.startsWith('+++ b/')) {
      const filename = line.substring(6).trim();
      filesChanged.push(filename);

      if (filename.endsWith('.md') || filename.includes('doc')) hasDocs = true;
      if (filename.includes('test') || filename.includes('spec')) hasTests = true;
    }

    if (line.startsWith('+') && !line.startsWith('+++')) {
      additions++;
      const lower = line.toLowerCase();
      if (lower.includes('fix') || lower.includes('bug') || lower.includes('patch') || lower.includes('error')) hasFix = true;
      if (lower.includes('feature') || lower.includes('function') || lower.includes('endpoint') || lower.includes('create')) hasFeat = true;
      if (lower.includes('refactor') || lower.includes('cleanup') || lower.includes('restructure')) hasRefactor = true;
    }

    if (line.startsWith('-') && !line.startsWith('---')) {
      deletions++;
    }
  }

  // Determine Type
  let type = 'chore';
  if (hasFix) type = 'fix';
  else if (hasFeat) type = 'feat';
  else if (hasRefactor) type = 'refactor';
  else if (hasTests) type = 'test';
  else if (hasDocs) type = 'docs';

  // Determine Primary Scope
  let scope = 'core';
  if (filesChanged.length > 0) {
    const firstFile = filesChanged[0];
    const parts = firstFile.split('/');
    if (parts.length > 1) {
      scope = parts[0];
    } else {
      scope = firstFile.split('.')[0] || 'core';
    }
  }

  // Determine Subject
  let actionVerb = 'update';
  if (type === 'feat') actionVerb = 'add implementation for';
  else if (type === 'fix') actionVerb = 'resolve issue in';
  else if (type === 'docs') actionVerb = 'update documentation for';
  else if (type === 'test') actionVerb = 'add test coverage for';

  const subject = `${actionVerb} ${scope}`;

  // Format full message according to style
  let fullMessage = `${type}(${scope}): ${subject}`;

  if (style === 'gitmoji') {
    const emojis = { feat: '✨', fix: '🐛', docs: '📝', test: '🧪', refactor: '♻️', chore: '🔧' };
    fullMessage = `${emojis[type] || '🔧'} ${type}(${scope}): ${subject}`;
  }

  // Pro feature: Detailed multi-line bullet points
  if (isPro && filesChanged.length > 1) {
    const bodyPoints = filesChanged.slice(0, 5).map(f => `- update \`${f}\``).join('\n');
    fullMessage += `\n\n${bodyPoints}\n\n[Verified by AI Commit Generator Pro]`;
  }

  return {
    type,
    scope,
    subject,
    fullMessage,
    stats: { filesCount: filesChanged.length, additions, deletions }
  };
}

export function generateChangelog(commitList = []) {
  const categories = { feat: [], fix: [], other: [] };

  for (const commit of commitList) {
    if (commit.startsWith('feat')) categories.feat.push(commit);
    else if (commit.startsWith('fix')) categories.fix.push(commit);
    else categories.other.push(commit);
  }

  let changelog = `## 📋 Release Notes (${new Date().toISOString().split('T')[0]})\n\n`;

  if (categories.feat.length > 0) {
    changelog += `### ✨ New Features\n` + categories.feat.map(c => `- ${c}`).join('\n') + `\n\n`;
  }
  if (categories.fix.length > 0) {
    changelog += `### 🐛 Bug Fixes\n` + categories.fix.map(c => `- ${c}`).join('\n') + `\n\n`;
  }
  if (categories.other.length > 0) {
    changelog += `### 🔧 Maintenance & Chores\n` + categories.other.map(c => `- ${c}`).join('\n') + `\n\n`;
  }

  changelog += `---\n*Generated by AI Commit & Changelog Generator | Binance Pay UID: 1049392123*\n`;
  return changelog;
}

export function validateLicenseKey(key) {
  if (!key || typeof key !== 'string') return false;
  const clean = key.trim().toUpperCase();
  // Validates official Binance transaction ID or generated Pro key
  return clean.startsWith('BPS-PRO-') || clean.startsWith('AICOMMIT-PRO-') || /^[0-9]{8,12}$/.test(clean);
}
